--[[
    Room3D - walk around a cozy bedroom (Crayon Engine)
    Models/textures are generated by tools/generate_room.py (already generated).

    Desktop : click to capture the mouse, mouse = look, WASD = move, SHIFT = run,
              arrow keys = look, ESC = release the mouse, H = hide/show help
    Touch   : drag on the LEFT half = move (virtual stick), drag on the RIGHT half = look
]]
local A = "assets/"
local VW, VH = 320, 240
local gfx
local M, TX = {}, {}
local font

local cam = { x = 3.9, y = 1.5, z = 3.7, yaw = -42, pitch = -5 }
local PLAYER_R = 0.26
local ROOM = { 0.3, 0.3, 5.7, 4.7 }          -- x0, z0, x1, z1 walkable area

local colliders = {
    -- BEGIN COLLIDERS
    { 0.00, 1.30, 0.75, 3.00 },
    { 0.80, 0.00, 1.60, 0.43 },
    { 3.45, 0.00, 6.00, 1.10 },
    { 0.78, 1.82, 1.42, 2.48 },
    { 0.05, 3.40, 0.40, 3.80 },
    -- END COLLIDERS
}

local captured, skipDelta, showHelp = false, false, true
local isTouch = false
local leftStart, lastRight = nil, nil
local moveStick = { x = 0, y = 0 }

local function clamp(v, a, b) return math.max(a, math.min(b, v)) end

local function resolve(x, z)
    x, z = clamp(x, ROOM[1], ROOM[3]), clamp(z, ROOM[2], ROOM[4])
    for _, b in ipairs(colliders) do
        local cx, cz = clamp(x, b[1], b[3]), clamp(z, b[2], b[4])
        local dx, dz = x - cx, z - cz
        local d2 = dx * dx + dz * dz
        if d2 < PLAYER_R * PLAYER_R then
            if d2 > 1e-9 then
                local d = math.sqrt(d2); x, z = cx + dx / d * PLAYER_R, cz + dz / d * PLAYER_R
            else   -- centre is inside the box: push out through the nearest side
                local l, r, t, bt = x - b[1], b[3] - x, z - b[2], b[4] - z
                local m = math.min(l, r, t, bt)
                if m == l then x = b[1] - PLAYER_R elseif m == r then x = b[3] + PLAYER_R
                elseif m == t then z = b[2] - PLAYER_R else z = b[4] + PLAYER_R end
            end
        end
    end
    return clamp(x, ROOM[1], ROOM[3]), clamp(z, ROOM[2], ROOM[4])
end

function crayon.config(t)
    t.identity = "Room3D"
    t.window = { title = "Room3D", width = 320, height = 240, virtualWidth = VW, virtualHeight = VH,
                 resizable = true, vsync = true, scaling = "aspect" }
    t.modules = { physics3D = false, physics2D = false, physics4D = false, audio = false, mesh3D = true, input = true }
    t.graphics = { clearColor = { 0.06, 0.05, 0.08, 1 } }
end

function crayon.init()
    gfx = crayon.graphics
    local function model(n) return gfx.loadModel(A .. "models/" .. n .. ".obj") end
    local function tex(n) return gfx.loadTexture(A .. "textures/" .. n .. ".png") end
    for _, n in ipairs({ "floor", "walls_warm", "walls_cool", "wood_brown", "wood_orange", "props", "crates", "speakers",
                         "curtain", "calendar", "mattress", "window_glow", "emissive", "sunpatch" }) do M[n] = model(n) end
    for _, n in ipairs({ "floor", "plaster_warm", "plaster_cool", "wood_brown", "wood_orange", "palette", "crate_face",
                         "speaker", "curtain", "calendar", "mattress", "glow", "sunpatch" }) do TX[n] = tex(n) end
    font = gfx.loadFont("res/IBMPlexSans-Bold.ttf", 16)
    pcall(function() isTouch = crayon.touch.isAvailable() and true or false end)
    
    crayon.graphics.setRetroEffects({
        affine = 0
    })
end

function crayon.touchdown() isTouch = true end

function crayon.update(dt)
    dt = math.min(dt, 0.05)
    local k, ms = crayon.key, crayon.mouse
    local lookX, lookY, mx, mz = 0, 0, 0, 0

    -- ---- mouse look
    if not captured and ms.isPressed(1) and not isTouch then
        captured = true; skipDelta = true; pcall(function() ms.setRelativeMode(true); ms.setVisible(false) end)
    end
    if captured then
        if k.isPressed("escape") then captured = false; pcall(function() ms.setRelativeMode(false); ms.setVisible(true) end)
        elseif skipDelta then skipDelta = false
        else local dx, dy = ms.getDelta(); lookX, lookY = dx * 0.1, dy * 0.1 end
    end
    if k.isDown("left") then lookX = lookX - 90 * dt end
    if k.isDown("right") then lookX = lookX + 90 * dt end
    if k.isDown("up") then lookY = lookY - 60 * dt end
    if k.isDown("down") then lookY = lookY + 60 * dt end
    if k.isPressed("h") then showHelp = not showHelp end

    -- ---- touch: left half = stick, right half = look
    moveStick.x, moveStick.y = 0, 0
    if isTouch then
        local ok, ts = pcall(function() return crayon.touch.getTouches() end)
        local left, right
        if ok and ts then for _, t in ipairs(ts) do if t.x < VW / 2 then left = left or t else right = right or t end end end
        if left then
            leftStart = leftStart or { x = left.x, y = left.y }
            moveStick.x = clamp((left.x - leftStart.x) / 90, -1, 1); moveStick.y = clamp((left.y - leftStart.y) / 90, -1, 1)
        else leftStart = nil end
        if right then
            if lastRight then lookX = lookX + (right.x - lastRight.x) * 0.2; lookY = lookY + (right.y - lastRight.y) * 0.2 end
            lastRight = { x = right.x, y = right.y }
        else lastRight = nil end
    end
    cam.yaw = cam.yaw + lookX
    cam.pitch = clamp(cam.pitch - lookY, -85, 85)

    -- ---- walking
    if k.isDown("w") then mz = mz + 1 end
    if k.isDown("s") then mz = mz - 1 end
    if k.isDown("d") then mx = mx + 1 end
    if k.isDown("a") then mx = mx - 1 end
    mx, mz = mx + moveStick.x, mz - moveStick.y
    local len = math.sqrt(mx * mx + mz * mz)
    if len > 1 then mx, mz = mx / len, mz / len end
    local speed = (k.isDown("lshift", "rshift") and 3.4 or 1.9)
    local yaw = math.rad(cam.yaw)
    local fx, fz = math.sin(yaw), -math.cos(yaw)
    local rx, rz = math.cos(yaw), math.sin(yaw)
    cam.x, cam.z = resolve(cam.x + (fx * mz + rx * mx) * speed * dt, cam.z + (fz * mz + rz * mx) * speed * dt)
end

function crayon.draw()
    gfx.clear(0.06, 0.05, 0.08)
    local yaw, pit = math.rad(cam.yaw), math.rad(cam.pitch)
    gfx.setCamera3D({ position = { cam.x, cam.y, cam.z },
                      target = { cam.x + math.cos(pit) * math.sin(yaw), cam.y + math.sin(pit), cam.z - math.cos(pit) * math.cos(yaw) },
                      up = { 0, 1, 0 }, fov = 70, near = 0.05, far = 60 })
    gfx.setCullFace(false)
    gfx.setShadingMode("gouraud")
    -- warm evening sun through the window, purple ambient, desk lamp glow
    gfx.setLight(0.35, -0.55, 0.75, 0.55, 0.38, 0.22, 0.36, 0.31, 0.42)
    gfx.setPointLight(0, 3.6, 1.4, 0.6, 1.0, 0.72, 0.38, 7, 1.6)
    gfx.setPointLight(1, 0.45, 1.1, 1.85, 1.0, 0.85, 0.55, 2.6, 1.2)
    gfx.setPointLightEnabled(0, true); gfx.setPointLightEnabled(1, true)
    gfx.setColor(1, 1, 1, 1)

    local function d(m, t) gfx.drawModel(M[m], 0, 0, 0, 0, 0, 0, 1, 1, 1, TX[t]) end
    d("floor", "floor"); d("walls_warm", "plaster_warm"); d("walls_cool", "plaster_cool")
    d("wood_brown", "wood_brown"); d("wood_orange", "wood_orange"); d("props", "palette")
    d("crates", "crate_face"); d("speakers", "speaker"); d("curtain", "curtain"); d("calendar", "calendar"); d("mattress", "mattress")

    gfx.setShadingMode("unlit")
    d("window_glow", "glow"); d("emissive", "palette")
    gfx.setBlendMode("alpha"); d("sunpatch", "sunpatch")
    gfx.setShadingMode("gouraud")

    -- HUD
    gfx.setColor(1, 1, 1, 0.8); gfx.drawCircle("fill", VW / 2, VH / 2, 2, 8)
    gfx.setFont(font)
    if showHelp then
        gfx.setColor(1, 1, 1, 0.7)
        if isTouch then gfx.drawText("Left half: move   |   Right half: look around", 16, VH - 28, 1)
        elseif captured then gfx.drawText("WASD move  |  SHIFT run  |  Mouse / arrows look  |  ESC release mouse  |  H hide help", 16, VH - 28, 1)
        else gfx.drawText("Click to look around  |  WASD move  |  arrows look  |  H hide help", 16, VH - 28, 1) end
    end
end
