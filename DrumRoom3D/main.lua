-- ---------------------------------------------------------------- picking (ray vs. drum shapes)

-- Normalize whatever the engine hands us for origin / direction
-- into a plain {x=, y=, z=} table. Returns nil if we can't figure it out.
local function normVec(v)
    if type(v) ~= "table" then return nil end
    local x, y, z = v.x, v.y, v.z
    if x == nil then x = v[1] end
    if y == nil then y = v[2] end
    if z == nil then z = v[3] end
    if x == nil or y == nil or z == nil then return nil end
    return { x = x, y = y, z = z }
end

local function raySphere(o, d, p)
    local c = p.c
    local ox, oy, oz = o.x - c[1], o.y - c[2], o.z - c[3]
    local b = ox * d.x + oy * d.y + oz * d.z
    local cc = ox * ox + oy * oy + oz * oz - p.r * p.r
    local disc = b * b - cc
    if disc < 0 then return nil end
    local t = -b - math.sqrt(disc)
    if t > 0 then return t, 0, 0 end
    return nil
end

-- finite capped cylinder; returns t, axial position s, radial fraction rho (1 on the side wall)
local function rayCyl(o, d, p)
    local c, a = p.c, p.a
    local px, py, pz = o.x - c[1], o.y - c[2], o.z - c[3]
    local pa = px * a[1] + py * a[2] + pz * a[3]
    local da = d.x * a[1] + d.y * a[2] + d.z * a[3]
    local qx, qy, qz = px - pa * a[1], py - pa * a[2], pz - pa * a[3]
    local ex, ey, ez = d.x - da * a[1], d.y - da * a[2], d.z - da * a[3]
    local best, bs, br
    local qa = ex * ex + ey * ey + ez * ez
    local qb = 2 * (qx * ex + qy * ey + qz * ez)
    local qc = qx * qx + qy * qy + qz * qz - p.r * p.r
    if qa > 1e-9 then
        local disc = qb * qb - 4 * qa * qc
        if disc >= 0 then
            local sq = math.sqrt(disc)
            for _, t in ipairs({ (-qb - sq) / (2 * qa), (-qb + sq) / (2 * qa) }) do
                if t > 0 then
                    local s = pa + t * da
                    if math.abs(s) <= p.h and (not best or t < best) then best, bs, br = t, s, 1 end
                end
            end
        end
    end
    if math.abs(da) > 1e-9 then
        for _, sg in ipairs({ -1, 1 }) do
            local t = (sg * p.h - pa) / da
            if t > 0 and (not best or t < best) then
                local rx, ry, rz = qx + t * ex, qy + t * ey, qz + t * ez
                local rho = math.sqrt(rx * rx + ry * ry + rz * rz) / p.r
                if rho <= 1 then best, bs, br = t, sg * p.h, rho end
            end
        end
    end
    return best, bs, br
end

local function pick(sx, sy)
    local ray = gfx.getCameraRay(sx, sy)
    if not ray then return nil end

    local o = normVec(ray.origin) or normVec(ray.o) or normVec(ray[1])
    local d = normVec(ray.direction) or normVec(ray.dir) or normVec(ray[2])
    if not o or not d then return nil end

    local bestT, bestId, bs, br
    for id, p in pairs(PARTS) do
        local t, s, rho
        if p.shape == "sphere" then t, s, rho = raySphere(o, d, p)
        else t, s, rho = rayCyl(o, d, p) end
        if t and (not bestT or t < bestT) then bestT, bestId, bs, br = t, id, s, rho end
    end
    if not bestId then return nil end
    local p, zone = PARTS[bestId], nil
    if bestId == "snare" and bs > p.h - 0.035 and br > 0.8 then zone = "rim" end
    if bestId == "ride" and br < 0.22 then zone = "bell" end
    return bestId, zone
end

-- ---------------------------------------------------------------- playing
local hitT = {}
local labels = {}
local hatOpen, hatVoice = false, nil

local function play(name, vol, pitch, pan)
    local id = SND[name]
    if not id then return nil end
    local ok, v = pcall(function() return au.playSound(id, { volume = vol or 1, pitch = pitch or 1, pan = pan or 0 }) end)
    return ok and v or nil
end

local function trigger(id, zone, pan)
    local p = PARTS[id]
    if not p then return end
    local pitch = 0.97 + math.random() * 0.06
    local vol = 0.85 + math.random() * 0.15
    local label = p.name
    if id == "kick" or id == "kickpedal" then id = "kick"; play("kick", vol, pitch, pan)
    elseif id == "snare" then
        if zone == "rim" then play("snare_rim", vol, pitch, pan); label = "Snare (rim)" else play("snare", vol, pitch, pan) end
    elseif id == "tom1" or id == "tom2" or id == "floortom" then play(id, vol, pitch, pan)
    elseif id == "crash" then play("crash", vol, pitch, pan)
    elseif id == "ride" then
        if zone == "bell" then play("ride_bell", vol, pitch, pan); label = "Ride (bell)" else play("ride", vol, pitch, pan) end
    elseif id == "hihat" then
        if hatVoice then pcall(function() au.stopSound(hatVoice) end); hatVoice = nil end
        if hatOpen then hatVoice = play("hat_open", vol, pitch, pan); label = "Hi-hat (open)"
        else play("hat_closed", vol, pitch, pan); label = "Hi-hat (closed)" end
    elseif id == "hatpedal" then
        hatOpen = not hatOpen
        if hatVoice then pcall(function() au.stopSound(hatVoice) end); hatVoice = nil end
        play("hat_pedal", 0.8, 1, pan)
        label = hatOpen and "Hi-hat OPEN" or "Hi-hat CLOSED"
        id = "hihat"
    end
    hitT[id] = 0
    local c = PARTS[id] and PARTS[id].c or p.c
    labels[#labels + 1] = { text = label, x = c[1], y = c[2] + 0.3, z = c[3], t = 0 }
    if #labels > 6 then table.remove(labels, 1) end
end

local KEYMAP = { space = { "kick" }, j = { "snare" }, b = { "snare", "rim" }, u = { "tom1" }, i = { "tom2" }, o = { "floortom" },
                 k = { "hihat" }, m = { "hatpedal" }, l = { "crash" }, p = { "ride" }, n = { "ride", "bell" } }

-- auto beat (T)
local demo, demoT, demoStep = false, 0, 0
local BEAT = { { "kick", "hihat" }, { "hihat" }, { "hihat", "snare" }, { "hihat" }, { "kick", "hihat" }, { "kick", "hihat" }, { "hihat", "snare" }, { "hihat", "tom1" } }
local function runDemo(dt)
    if not demo then return end
    demoT = demoT + dt
    local stepLen = 60 / 112 / 2
    while demoT >= stepLen do
        demoT = demoT - stepLen
        for _, id in ipairs(BEAT[demoStep % 8 + 1]) do trigger(id, nil, 0) end
        if demoStep % 32 == 0 then trigger("crash", nil, 0) end
        demoStep = demoStep + 1
    end
end

-- ---------------------------------------------------------------- input state
local showHelp, looking = true, false
local isTouch = false
local leftStart, lastRight = nil, nil
local moveStick = { x = 0, y = 0 }
local pending = nil
local touchPrev, touchStartT, touchStartPos, touchMoved = false, 0, nil, false
local clock = 0

function crayon.init()
    gfx, au = crayon.graphics, crayon.audio
    local function model(n) return gfx.loadModel(A .. "models/" .. n .. ".obj") end
    local function tex(n) return gfx.loadTexture(A .. "textures/" .. n .. ".png") end
    for _, n in ipairs({ "floor", "rug", "walls_a", "walls_b", "foam", "props", "speakers", "amp_face", "poster1", "poster2", "curtain",
                         "window_glow", "emissive", "sunpatch", "kit_hw", "kick", "snare", "tom1", "tom2", "floortom", "hat_top" }) do M[n] = model(n) end
    for _, c in ipairs({ "crash", "ride" }) do for v = 0, 8 do M[c .. "_" .. v] = model(c .. "_" .. v) end end
    for _, n in ipairs({ "floor", "rug", "plaster_a", "plaster_b", "room_palette", "speaker", "amp_face", "poster1", "poster2", "curtain",
                         "glow", "sunpatch", "kit" }) do TX[n] = tex(n) end
    for _, n in ipairs({ "kick", "snare", "snare_rim", "tom1", "tom2", "floortom", "hat_closed", "hat_open", "hat_pedal", "crash", "ride", "ride_bell" }) do
        local ok, id = pcall(function() return au.loadSound(A .. "sounds/" .. n .. ".wav") end)
        if ok then SND[n] = id end
    end
    for id in pairs(PARTS) do hitT[id] = 99 end
    font = gfx.loadFont("res/IBMPlexSans-Bold.ttf", 16)
    pcall(function() isTouch = crayon.touch.isAvailable() and true or false end)
    gfx.setRetroEffects({ affine = 0 })
end

function crayon.touchdown() isTouch = true end

function crayon.keydown(key, isRepeat)
    if isRepeat then return end
    local km = KEYMAP[key]
    if km then trigger(km[1], km[2], 0)
    elseif key == "t" then demo = not demo; demoT = 0; demoStep = 0
    elseif key == "h" then showHelp = not showHelp end
end

function crayon.update(dt)
    dt = math.min(dt, 0.05); clock = clock + dt
    local k, ms = crayon.key, crayon.mouse
    local lookX, lookY, mx, mz = 0, 0, 0, 0
    for id in pairs(hitT) do hitT[id] = hitT[id] + dt end
    for i = #labels, 1, -1 do labels[i].t = labels[i].t + dt; if labels[i].t > 1.1 then table.remove(labels, i) end end
    runDemo(dt)

    if not isTouch then
        if ms.isPressed(1) then pending = { ms.getPosition() } end
        if ms.isPressed(3) then looking = true; pcall(function() ms.setRelativeMode(true); ms.setVisible(false) end) end
        if looking and ms.isReleased(3) then looking = false; pcall(function() ms.setRelativeMode(false); ms.setVisible(true) end) end
        if looking then local dx, dy = ms.getDelta(); lookX, lookY = dx * 0.12, dy * 0.12 end
    end
    if k.isDown("left") then lookX = lookX - 90 * dt end
    if k.isDown("right") then lookX = lookX + 90 * dt end
    if k.isDown("up") then lookY = lookY - 60 * dt end
    if k.isDown("down") then lookY = lookY + 60 * dt end

    moveStick.x, moveStick.y = 0, 0
    if isTouch then
        local ok, ts = pcall(function() return crayon.touch.getTouches() end)
        local left, right, count = nil, nil, 0
        if ok and ts then for _, t in ipairs(ts) do count = count + 1; if t.x < VW / 2 then left = left or t else right = right or t end end end
        local first = (ok and ts and ts[1]) or nil
        if count == 1 and not touchPrev then touchStartT, touchStartPos, touchMoved = clock, { first.x, first.y }, false end
        if count >= 1 and touchStartPos and first then
            if math.abs(first.x - touchStartPos[1]) + math.abs(first.y - touchStartPos[2]) > 14 then touchMoved = true end
        end
        if count == 0 and touchPrev and touchStartPos and not touchMoved and clock - touchStartT < 0.35 then
            pending = { touchStartPos[1], touchStartPos[2] }
        end
        touchPrev = count >= 1
        if left then
            leftStart = leftStart or { x = left.x, y = left.y }
            moveStick.x = clamp((left.x - leftStart.x) / 90, -1, 1); moveStick.y = clamp((left.y - leftStart.y) / 90, -1, 1)
        else leftStart = nil end
        if right then
            if lastRight then lookX = lookX + (right.x - lastRight.x) * 0.2; lookY = lookY + (right.y - lastRight.y) * 0.2 end
            lastRight = { x = right.x, y = right.y }
        else lastRight = nil end
    end
    cam.yaw = cam.yaw + lookX
    cam.pitch = clamp(cam.pitch - lookY, -85, 85)

    if k.isDown("w") then mz = mz + 1 end
    if k.isDown("s") then mz = mz - 1 end
    if k.isDown("d") then mx = mx + 1 end
    if k.isDown("a") then mx = mx - 1 end
    mx, mz = mx + moveStick.x, mz - moveStick.y
    local len = math.sqrt(mx * mx + mz * mz)
    if len > 1 then mx, mz = mx / len, mz / len end
    local speed = (k.isDown("lshift", "rshift") and 3.4 or 1.9)
    local yaw = math.rad(cam.yaw)
    local fx, fz = math.sin(yaw), -math.cos(yaw)
    local rx, rz = math.cos(yaw), math.sin(yaw)
    cam.x, cam.z = resolve(cam.x + (fx * mz + rx * mx) * speed * dt, cam.z + (fz * mz + rz * mx) * speed * dt)
end

function crayon.draw()
    gfx.clear(0.06, 0.05, 0.08)
    local yaw, pit = math.rad(cam.yaw), math.rad(cam.pitch)
    gfx.setCamera3D({ position = { cam.x, cam.y, cam.z },
                      target = { cam.x + math.cos(pit) * math.sin(yaw), cam.y + math.sin(pit), cam.z - math.cos(pit) * math.cos(yaw) },
                      up = { 0, 1, 0 }, fov = 65, near = 0.05, far = 30 })

    if pending then
        local id, zone = pick(pending[1], pending[2])
        if id then trigger(id, zone, clamp((pending[1] / VW - 0.5) * 0.8, -0.8, 0.8)) end
        pending = nil
    end

    gfx.setCullFace("back")
    gfx.setShadingMode("gouraud")
    gfx.setLight(SUN[1], SUN[2], SUN[3], 0.6, 0.45, 0.28, 0.40, 0.36, 0.45)
    gfx.setPointLight(0, 3.2, 2.0, 2.1, 1.0, 0.85, 0.6, 7.5, 1.5)
    gfx.setPointLight(1, 3.2, 1.9, 4.6, 0.7, 0.8, 1.0, 6.5, 1.1)
    gfx.setPointLightEnabled(0, true); gfx.setPointLightEnabled(1, true)
    gfx.setColor(1, 1, 1, 1)

    local function d(m, t, x, y, z, sx, sy, sz) gfx.drawModel(M[m], x or 0, y or 0, z or 0, 0, 0, 0, sx or 1, sy or 1, sz or 1, TX[t]) end
    d("floor", "floor"); d("rug", "rug"); d("walls_a", "plaster_a"); d("walls_b", "plaster_b"); d("foam", "room_palette")
    d("props", "room_palette"); d("speakers", "speaker"); d("amp_face", "amp_face"); d("poster1", "poster1"); d("poster2", "poster2"); d("curtain", "curtain")

    d("kit_hw", "kit")
    for _, n in ipairs({ "kick", "snare", "tom1", "tom2", "floortom" }) do
        local p = PARTS[n]; local s = 1 + 0.035 * math.exp(-hitT[n] * 14)
        d(n, "kit", p.c[1], p.c[2], p.c[3], s, s, s)
    end
    local h = PARTS.hihat
    d("hat_top", "kit", h.c[1], h.c[2] + (hatOpen and 0.04 or 0) - 0.014 * math.exp(-hitT.hihat * 25), h.c[3])
    for _, n in ipairs({ "crash", "ride" }) do
        local p, t = PARTS[n], hitT[n]
        local v = 0
        if t < 1.6 then v = 1 + math.floor((t * 15) % 8) end
        d(n .. "_" .. v, "kit", p.c[1], p.c[2] - 0.012 * math.exp(-t * 18), p.c[3])
    end

    gfx.setShadingMode("unlit")
    d("window_glow", "glow"); d("emissive", "room_palette")
    gfx.setBlendMode("alpha"); d("sunpatch", "sunpatch")
    gfx.setShadingMode("gouraud")

    gfx.setFont(font)
    for _, l in ipairs(labels) do
        local sx, sy, vis = gfx.project(l.x, l.y + l.t * 0.15, l.z)
        if vis then
            local a = clamp(1.1 - l.t, 0, 1)
            gfx.setColor(0, 0, 0, a * 0.6); gfx.drawText(l.text, sx - 29, sy + 1, 1)
            gfx.setColor(1, 0.92, 0.3, a); gfx.drawText(l.text, sx - 30, sy, 1)
        end
    end
    gfx.setColor(1, 1, 1, 0.75)
    gfx.drawText(hatOpen and "Hi-hat: OPEN" or "Hi-hat: closed", 6, 5, 1)
    if showHelp then
        if isTouch then gfx.drawText("Tap drums to play  |  Left: walk  |  Right: look", 6, VH - 16, 1)
        else
            gfx.drawText("Click drums  |  RMB look  |  WASD walk  |  T beat  |  H help", 6, VH - 26, 1)
            gfx.drawText("SPACE kick  J snare  B rim  UIO toms  K hat  M hat OC  L crash  P ride  N bell", 6, VH - 14, 1)
        end
    end
end